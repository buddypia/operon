pub(crate) fn translation_for(language: Language, message: &str) -> Option<&'static str> {
    let table = match language {
        // Japanese is the identity mapping and owns no table: the message id
        // *is* the copy. Saying so with `None` leaves the caller's fallback —
        // the id itself — as the single place that answer is written.
        Language::Ja => return None,
        Language::En => EN_TABLE,
        Language::Ko => KO_TABLE,
    };
    let found = table
        .binary_search_by(|(key, _)| (*key).cmp(message))
        .ok()?;
    Some(table[found].1)
}

/// Every message id any table knows about, for the drift tests. The union
/// rather than one table's keys: an id that reached only the Korean table is
/// exactly the half-finished row those tests exist to find.
#[cfg(test)]
pub(crate) fn catalog_keys() -> impl Iterator<Item = &'static str> {
    EN_TABLE.iter().chain(KO_TABLE.iter()).map(|(key, _)| *key)
}
